def _extract_script(deliverable, workdir):
    if not os.path.exists(deliverable):
        raise AssertionError("deliverable not found: %s" % deliverable)
    td = tempfile.mkdtemp(prefix="_chk_", dir=workdir if os.path.isdir(workdir) else None)
    try:
        with zipfile.ZipFile(deliverable) as z:
            names = z.namelist()
            if SCRIPT_NAME not in names:
                raise AssertionError("a: %s not in zip (names=%s)" % (SCRIPT_NAME, names))
            z.extract(SCRIPT_NAME, td)
        sp = os.path.join(td, SCRIPT_NAME)
        try:
            py_compile.compile(sp, doraise=True)
        except py_compile.PyCompileError as e:
            raise AssertionError("a: py_compile failed: %s" % e)
        return sp, td
    except AssertionError:
        shutil.rmtree(td, ignore_errors=True); raise
    except Exception as e:
        shutil.rmtree(td, ignore_errors=True); raise AssertionError("a: extract error: %s" % e)

def _run(sp, rp, setting, netlist, workdir, outname="out.json"):
    out = os.path.join(workdir, outname)
    if os.path.exists(out): os.remove(out)
    p = subprocess.run([sys.executable, sp, rp, setting, netlist, "-o", out],
                       capture_output=True, text=True, timeout=60, cwd=workdir)
    if p.returncode != 0:
        raise AssertionError("script run rc=%d stderr=%s" % (p.returncode, p.stderr[:500]))
    if not os.path.exists(out):
        raise AssertionError("output json not produced")
    try:
        with open(out) as f: return json.load(f)
    except Exception as e:
        raise AssertionError("b: output not valid JSON (%s)" % type(e).__name__)

