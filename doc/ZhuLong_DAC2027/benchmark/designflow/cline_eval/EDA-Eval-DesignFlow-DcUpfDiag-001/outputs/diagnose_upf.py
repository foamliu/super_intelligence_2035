#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""diagnose_upf.py -- generic DC UPF / save_upf diagnostic tool.

Usage:
    python3 diagnose_upf.py <bundle_root> [-o out.json]

Scans a Design Compiler synthesis bundle (the .tcl driver, the golden UPF
power-intent, the setup tcl, dc.log run log, UPF load echo, the save_upf
output, the post-synthesis netlist head and the RTL top port section) and emits
a structured `diagnosis.json` explaining two classic symptoms:

  1. save_upf_empty -- why the `save_upf` output file is (nearly) empty.
  2. netlist_no_pg  -- why the synthesized netlist has no VDD/VSS (PG) pins.

The tool is generic and adaptive: it discovers and classifies files by CONTENT
rather than by hard-coded file/design names, and derives each root cause from
the signals it actually observes (save_upf -supplemental vs golden UPF, the
write -format verilog options, presence of PG nets/pins, MV-cell insertion
reports, etc.). Pure standard library only.
"""

import argparse
import json
import os
import re
import sys


def _read_text(path):
    for enc in ("utf-8", "latin-1"):
        try:
            with open(path, "r", encoding=enc) as fh:
                return fh.read()
        except (UnicodeDecodeError, OSError):
            continue
    with open(path, "rb") as fh:
        return fh.read().decode("latin-1", "replace")


def _walk(root):
    out = []
    for dirpath, _d, names in os.walk(root):
        for n in names:
            full = os.path.join(dirpath, n)
            out.append((os.path.relpath(full, root), full))
    return sorted(out)


def _base(rel):
    return os.path.basename(rel) if rel else "?"


class Bundle(object):
    """Discovers and classifies the files of a DC synthesis bundle."""

    def __init__(self, root):
        self.root = root
        self.text = {}
        for rel, full in _walk(root):
            self.text[rel] = _read_text(full)
        self.dc_tcl = None
        self.setup_tcl = None
        self.golden_upf = None
        self.saved_upf = None
        self.dc_log = None
        self.upf_log = None
        self.rtl_v = None
        self.postsyn_v = None
        self._classify()

    def _ext(self, rel):
        return os.path.splitext(rel)[1].lower()

    def _classify(self):
        texts = self.text
        tcls = [r for r in texts if self._ext(r) == ".tcl"]
        drv = [r for r in tcls if "save_upf" in texts[r] or "load_upf" in texts[r]
               or "compile_ultra" in texts[r]]
        if drv:
            drv.sort(key=lambda r: (("save_upf" in texts[r]),
                                    ("load_upf" in texts[r]),
                                    ("compile_ultra" in texts[r])), reverse=True)
            self.dc_tcl = drv[0]
        setup = [r for r in tcls if r != self.dc_tcl and
                 ("set DESIGN_NAME" in texts[r] or "set UPF_FILE" in texts[r]
                  or "SETUP_DIR" in texts[r] or "set RTL_SOURCE_FILES" in texts[r])]
        self.setup_tcl = setup[0] if setup else None

        upfs = [r for r in texts if self._ext(r) == ".upf"]
        saved = [r for r in upfs if "Supplemental UPF" in texts[r]
                 or "Generated by Design Compiler" in texts[r]]
        self.saved_upf = saved[0] if saved else None
        sources = [r for r in upfs if r not in saved]

        merged = (texts.get(self.dc_tcl, "") or "") + "\n" + (texts.get(self.setup_tcl, "") or "")
        ref = None
        m = re.search(r"\bset\s+UPF_FILE\s+\"?([^\"\s]+)\"?", merged)
        if m:
            ref = os.path.basename(m.group(1))
        if not ref:
            m = re.search(r"\bload_upf\s+\"?([^\"\s${}]+)\"?", texts.get(self.dc_tcl, "") or "")
            if m:
                ref = os.path.basename(m.group(1))
        golden = None
        if ref:
            for r in sources:
                if os.path.basename(r) == ref or os.path.basename(r).endswith(ref):
                    golden = r
                    break
        if golden is None and sources:
            golden = sorted(sources, key=lambda r: (
                ("create_power_domain" in texts[r]) + ("create_supply_port" in texts[r])),
                reverse=True)[0]
        self.golden_upf = golden

        logs = [r for r in texts if self._ext(r) == ".log"]
        runlog = [r for r in logs if "save_upf" in texts[r] or "compile_ultra" in texts[r]
                  or "write -format" in texts[r]]
        self.dc_log = runlog[0] if runlog else None
        uplog = [r for r in logs if "Begin loading UPF" in texts[r] or "upf_version" in texts[r]]
        self.upf_log = uplog[0] if uplog else None

        vs = [r for r in texts if self._ext(r) == ".v"]
        rtl = [r for r in vs if "always @" in texts[r] or "assign " in texts[r]]
        post = [r for r in vs if r not in rtl]
        self.rtl_v = rtl[0] if rtl else None
        self.postsyn_v = post[0] if post else None

    def save_upf_line(self):
        t = self.text.get(self.dc_tcl, "") if self.dc_tcl else ""
        for line in t.splitlines():
            s = line.strip()
            if s.startswith("save_upf"):
                return s
        return ""

    def write_netlist_line(self):
        t = self.text.get(self.dc_tcl, "") if self.dc_tcl else ""
        for line in t.splitlines():
            s = line.strip()
            if s.startswith("write ") or s.startswith("write_verilog"):
                return s
        return ""


def _mv_all_zero(log):
    hits = re.findall(
        r"\b(\d+)\s+(repeater|isolation|level shifters?|retention)\s*(?:cells?)?\s*inserted",
        log or "")
    if not hits:
        return True
    return all(int(c) == 0 for c, _ in hits)


def _strip_comments(text):
    return [ln for ln in (text or "").splitlines() if ln.strip() and not ln.strip().startswith("#")]


def diagnose_save_upf(b):
    saved = b.text.get(b.saved_upf, "") if b.saved_upf else ""
    golden = b.text.get(b.golden_upf, "") if b.golden_upf else ""
    dc = b.text.get(b.dc_tcl, "") if b.dc_tcl else ""
    log = b.text.get(b.dc_log, "") if b.dc_log else ""
    save_line = b.save_upf_line()

    body = _strip_comments(saved)
    empty = not body
    supplemental = bool(re.search(r"\bsupplemental\b", save_line or ""))
    idx = dc.find("enable_golden_upf")
    golden_enabled = idx >= 0 and bool(re.search(r"\btrue\b", dc[idx:idx + 80]))
    strat = re.compile(
        r"create_isolation|set_isolation|create_level_shifter|set_level_shifter|"
        r"create_retention|set_retention|add_isolation|add_level_shifter|add_retention")
    strategies = bool(strat.search(golden)) or bool(strat.search(dc))
    mv_zero = _mv_all_zero(log)

    if not empty:
        return {
            "root_cause": "save_upf 输出非空：已检测到 save_upf 正常写入了实质 UPF 命令。",
            "mechanism": "save_upf 生成的内容包含 create/connect/set 等 UPF 命令，说明电源意图或增量被正确导出。",
            "evidence": ["%s: 检测到 %d 个非注释的 UPF 命令" % (_base(b.saved_upf), len(body))],
            "fix": "无需修复。",
            "is_defect": False,
        }

    evidence = []
    if b.saved_upf:
        evidence.append("%s: save_upf 输出只有头部注释，没有任何 create/connect/set 等实质 UPF 命令（0 个非注释行）" % _base(b.saved_upf))
    if supplemental:
        evidence.append("%s: save_upf 调用带 -supplemental，只导出相对 golden UPF 的增量" % _base(b.dc_tcl))
    if golden_enabled:
        evidence.append("%s: upf.enable_golden_upf=true，load_upf 的 UPF 被当作 golden 基线" % _base(b.dc_tcl))
    if not strategies:
        evidence.append("%s: 电源意图未定义 isolation/level-shifter/retention 策略" % _base(b.golden_upf))
    if mv_zero:
        evidence.append("%s: 报告中 0 个 isolation/LS/retention/repeater 单元被插入，无派生的 supply exception 可导出" % _base(b.dc_log))

    if supplemental and golden_enabled:
        return {
            "root_cause":
                "save_upf 使用了 -supplemental 且 upf.enable_golden_upf=true：-supplemental 只写出相对 "
                "golden UPF 的增量（派生的 supply exception、插入的 MV 单元、电源状态变化），而本流程综合前后 "
                "没有任何这类增量，因此输出文件只剩头部注释，表现为“空”。",
            "mechanism":
                "开启 golden UPF 后，load_upf 把源 UPF 注册为参考基线；save_upf -supplemental 只 dump 新增意图。"
                "由于电源意图未定义 isolation/level-shifter/retention 策略、各域电压相同（无跨域 level shifter 需求），"
                "compile 阶段 0 个 MV 单元被插入、也没有派生出新的 supply exception，增量集合为空，所以 save_upf "
                "输出文件里没有任何 UPF 命令（dc.upf 仅为注释头）。",
            "evidence": evidence,
            "fix":
                "改用完整导出：save_upf 去掉 -supplemental（例如 'save_upf ${FINAL_UPF}' 或不带 -supplemental 的 "
                "'save_upf -include_supply_exceptions ...'）。若确实只要增量 UPF，则需先在 UPF 中定义 "
                "isolation/level-shifter/retention 策略或显式 supply exception，否则增量 UPF 合法地为空。",
            "is_defect": False,
        }
    if supplemental and not golden_enabled:
        return {
            "root_cause": "save_upf 使用 -supplemental 但未启用 golden UPF 基线，supplemental 模式无相对基线可 diff。",
            "mechanism": "增量(supplemental)导出要求先以 upf.enable_golden_upf=true 加载 golden UPF 作为基线；无基线时无增量可写。",
            "evidence": evidence,
            "fix": "在 load_upf 前 set_app_options upf.enable_golden_upf true，或去掉 -supplemental 做完整导出。",
            "is_defect": True,
        }
    return {
        "root_cause": "save_upf 输出为空但未使用 -supplemental：UPF 可能未成功加载或设计无电源意图。",
        "mechanism": "未采用 supplemental 模式却无输出，通常是 load_upf 未生效/被跳过，或综合前没有电源意图可供导出。",
        "evidence": evidence,
        "fix": "检查 load_upf 是否在 link 之后执行且未报错，确认 UPF 路径正确。",
        "is_defect": True,
    }

def diagnose_netlist_pg(b):
    dc = b.text.get(b.dc_tcl, "") if b.dc_tcl else ""
    post = b.text.get(b.postsyn_v, "") if b.postsyn_v else ""
    rtl = b.text.get(b.rtl_v, "") if b.rtl_v else ""
    write_line = b.write_netlist_line()

    has_pg = bool(re.search(r"(\b-pg\b|\b--power\b|\b-power\b|\b-pg_pin\b)", write_line or ""))
    uses_vfmt = "write" in (write_line or "") and "verilog" in (write_line or "")
    pg_port = re.compile(r"\b(VDD|VSS|VDDI|VSSI|VDDH|VSSH|DVDD|DVSS|AVDD|AVSS|PWR|GND)\b", re.I)
    post_has_pg = bool(re.search(r"\.\s*(VDD|VSS|VDDI|VSSI|VDDH|VSSH)\s*\(", post)) or bool(
        pg_port.search(post[:3000] if post else ""))
    rtl_has_pg = bool(pg_port.search((rtl or "")[:3000]))

    evidence = []
    if write_line:
        evidence.append("%s: %s" % (_base(b.dc_tcl), write_line.strip()))
    if not has_pg and uses_vfmt:
        evidence.append("%s: 'write -format verilog' 未带 -pg，Verilog 写器默认省略 power/ground 引脚与 supply 连接" % _base(b.dc_tcl))
    if b.postsyn_v and not post_has_pg:
        evidence.append("%s: 模块端口与单元实例均无 VDD/VSS（无 .VDD()/.VSS() 连接）" % _base(b.postsyn_v))
    if b.rtl_v and not rtl_has_pg:
        evidence.append("%s: RTL 顶层端口段未声明 VDD/VSS supply 端口" % _base(b.rtl_v))

    if has_pg:
        return {
            "root_cause": "写网表命令已带 -pg，但成品网表仍缺 VDD/VSS，需检查 UPF supply net 是否真正连到设计。",
            "mechanism": "写网表请求了 PG，但若 UPF 未把 supply net 连到顶层端口/单元电源引脚，导出仍无 VDD/VSS。",
            "evidence": evidence,
            "is_defect": True,
        }
    if uses_vfmt and not has_pg:
        return {
            "root_cause":
                "网表由 'write -format verilog' 导出且未加 -pg：DC 的 Verilog 写器默认只输出功能引脚，"
                "不写 VDD/VSS 电源/地引脚及其 supply 连接，因此综合后网表没有 VDD/VSS。",
            "mechanism":
                "'write -format verilog'（不带 -pg）不会写出电源与地引脚；再加上顶层 RTL 没有声明 supply 端口，"
                "最终网表的模块端口和单元实例都不含 VDD/VSS。修复应在写网表命令追加 -pg（例如 "
                "'write -format verilog -pg -hierarchy -output ...'）。",
            "evidence": evidence,
            "is_defect": True,
        }
    return {
        "root_cause": "未发现 'write -format verilog' 类型的写网表命令，无法从驱动脚本推断 PG 缺失原因。",
        "mechanism": "需要进一步检查网表生成方式。",
        "evidence": evidence,
        "is_defect": True,
    }

def diagnose_latent(b):
    golden = b.text.get(b.golden_upf, "") if b.golden_upf else ""
    dc = b.text.get(b.dc_tcl, "") if b.dc_tcl else ""
    setup = b.text.get(b.setup_tcl, "") if b.setup_tcl else ""
    rtl = b.text.get(b.rtl_v, "") if b.rtl_v else ""
    post = b.text.get(b.postsyn_v, "") if b.postsyn_v else ""
    issues = []

    domains = sorted(set(re.findall(r"create_power_domain\s+(\S+)", golden)))
    set_dsn = sorted(set(re.findall(r"set_domain_supply_net\s+(\S+)", golden)))
    if domains and set_dsn and set(set_dsn).isdisjoint(set(domains)):
        issues.append({
            "id": "LAT-1",
            "severity": "high",
            "desc": "电源域 (%s) 没有通过 set_domain_supply_net/associate_supply_set 绑定 primary 电源；"
                    "set_domain_supply_net 作用在 '%s' 上（与 domain 名不一致，疑似 supply set / 域名写错），"
                    "导致各域未显式获得电源，DC 退回默认假设 VDD/VSS（UPF-405）。"
                    % (", ".join(domains), ", ".join(set_dsn)),
            "fix": "为每个电源域显式绑定电源：set_domain_supply_net <domain> -primary_power_net ... "
                   "-primary_ground_net ...，或将 set_domain_supply_net 的目标改成真实的 domain 名。",
        })

    used_doms = re.findall(r"-domain\s+(\S+)", golden)
    defined_doms = set(re.findall(r"create_supply_domain\s+(\S+)", golden))
    undef = sorted(set(d for d in used_doms if d not in defined_doms))
    if undef:
        issues.append({
            "id": "LAT-2",
            "severity": "high",
            "desc": "supply net 创建在未定义的 supply domain '%s' 中（create_supply_net -domain 引用它，"
                    "但没有 create_supply_domain 声明）。" % ", ".join(undef),
            "fix": "在用 -domain 引用前先 'create_supply_domain %s'，或去掉 -domain 让 net 落入合适的作用域。" % undef[0],
        })

    elems = re.findall(r"create_power_domain\s+\S+\s+.*?-elements\s+(\S+)", golden)
    for e in set(elems):
        if "/" in e and e not in rtl and e not in post:
            issues.append({
                "id": "LAT-3",
                "severity": "high",
                "desc": "create_power_domain 的 -elements 指向层次实例 '%s'，但提供的 RTL/网表中不存在该实例。" % e,
                "fix": "把 -elements 指向 elaborated 层次中真实存在的实例，或用 -include_scope 圈定已有的层次边界。",
            })

    if "FINAL_UPF" in setup and "FINAL_UPF" not in dc:
        issues.append({
            "id": "LAT-4",
            "severity": "medium",
            "desc": "设置脚本定义了 FINAL_UPF 输出路径变量，但驱动脚本 save_upf 硬编码输出文件名、从未引用 "
                    "${FINAL_UPF}，导致对该变量的修改不会生效。",
            "fix": "让 save_upf 使用 '${FINAL_UPF}' 作为输出路径，避免文件名硬编码不一致。",
        })

    for line in golden.splitlines():
        s = line.strip()
        if "set_port_attributes" in s and "," in s and s.startswith("#"):
            issues.append({
                "id": "LAT-5",
                "severity": "low",
                "desc": "被注释掉的 set_port_attributes 块用逗号分隔端口列表（{A,B,C}），若取消注释，Tcl/UPF 会把整个花括号组"
                        "当单一 token，导致属性未作用到预期端口。",
                "fix": "改用空格分隔的端口列表（如 -ports {A B C}）。",
            })
            break

    if post:
        outs = set()
        for mo in re.finditer(r"\.(ZN|Z|Y|Q|QN|CO|S|OUT)\s*\(\s*(\w+)\s*\)", post):
            outs.add(mo.group(2))
        if outs:
            for line in post.splitlines():
                s = line.strip()
                if s.startswith("input"):
                    names = re.findall(r"\b\w+\b", s.split("input", 1)[1])
                    bad = [n for n in names if n in outs]
                    if bad:
                        issues.append({
                            "id": "LAT-6",
                            "severity": "high",
                            "desc": "综合后网表把被单元驱动的输出端口声明为 input（如 %s），端口方向与驱动关系不一致。"
                                    % ", ".join(bad[:4]),
                            "fix": "重新生成网表/修正端口方向声明，使被驱动的端口声明为 output。",
                        })
                        break
    return issues

def build_diagnosis(b):
    return {
        "save_upf_empty": diagnose_save_upf(b),
        "netlist_no_pg": diagnose_netlist_pg(b),
        "latent_issues": diagnose_latent(b),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generic DC UPF / save_upf diagnostic.")
    ap.add_argument("bundle_root", help="root directory of the DC synthesis bundle")
    ap.add_argument("-o", "--out", default="diagnosis.json", help="output JSON path (default: diagnosis.json)")
    args = ap.parse_args(argv)

    if not os.path.isdir(args.bundle_root):
        sys.stderr.write("bundle root not found: %s\n" % args.bundle_root)
        return 2

    b = Bundle(args.bundle_root)
    result = build_diagnosis(b)
    out = os.path.abspath(args.out)
    if os.path.dirname(out):
        os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())